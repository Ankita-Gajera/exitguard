#!/usr/bin/env node
// Copies the ABIs and creation bytecode the web console needs from Foundry's `out/` into `docs/artifacts.js`,
// and the ethers bundle into `docs/vendor/`, so the console is a plain static site with no build step.
//
//   forge build && cd tools && npm install && node export-artifacts.mjs

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = join(HERE, "..");

const read = (file, name = file) => JSON.parse(readFileSync(join(ROOT, "out", `${file}.sol`, `${name}.json`), "utf8"));

// Contracts the console deploys need their bytecode; the rest only their ABI.
const deployable = ["ExitGuard", "ExitGuardReactive", "DemoDeployer"];
const abiOnly = ["DemoVault", "MockUSD", "TimelockController"];

const artifacts = {};

for (const name of deployable) {
    const { abi, bytecode } = read(name);
    artifacts[name] = { abi, bytecode: bytecode.object };
}

for (const name of abiOnly) {
    artifacts[name] = { abi: read(name).abi };
}

mkdirSync(join(ROOT, "docs", "vendor"), { recursive: true });

writeFileSync(
    join(ROOT, "docs", "artifacts.js"),
    `// Generated by tools/export-artifacts.mjs from the Foundry build. Do not edit by hand.\n` +
        `window.EXITGUARD_ARTIFACTS = ${JSON.stringify(artifacts)};\n`,
);

copyFileSync(
    join(HERE, "node_modules", "ethers", "dist", "ethers.umd.min.js"),
    join(ROOT, "docs", "vendor", "ethers.umd.min.js"),
);

console.log(`Wrote docs/artifacts.js (${Object.keys(artifacts).join(", ")}) and docs/vendor/ethers.umd.min.js`);
